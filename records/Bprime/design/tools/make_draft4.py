def main():
    assert not os.path.exists(OUT), '既にある（一度だけ）'
    b = open(SRC, 'rb').read()
    assert hashlib.sha256(b).hexdigest().upper()[:16] == SRC_SHA16, '草案3 の SHA が合わない'
    t = b.decode('utf-8')
    for old, new in R:
        n = t.count(old)
        assert n == 1, ('元の文の数が 1 でない', n, old[:60])
        t = t.replace(old, new)
    open(OUT, 'w', encoding='utf-8', newline=NL).write(t)
    print('ok', len(R), 'replacements | draft4 sha16', hashlib.sha256(t.encode('utf-8')).hexdigest().upper()[:16], '| lines', t.count(NL))


if __name__ == '__main__':
    main()
