def main(dry):
    if not dry:
        assert not os.path.exists(OUT), '既にある（一度だけ）'
    t = b.decode('utf-8')
    for old, new in R:
        n = t.count(old)
        assert n == 1, ('元の文の数が 1 でない', n, old[:60])
        t = t.replace(old, new)
    t2 = TY.sp(t)
    changed = [(x, y) for x, y in zip(t.split(NL), t2.split(NL)) if x != y]
    print('字の体裁で変わった行 %d' % len(changed))
    t = t2
    assert not TY.tight(t), ('空白の無い置き場が残った', TY.tight(t)[:10])
    for new in ('〔V01〕', '〔V02・D282〕', '〔V10〕', '〔V13〕', '〔V16〕', '〔S16・D278〕', '〔D278〕', '| K28 |', '| V01 |', '| V10・V13・V16 |', 'rulings-D283.md', '草案12'):
        assert new in t, new
    assert '決め（案 16）になったときは' not in t, '案16 の条件の字が残った'
    sha = hashlib.sha256(t.encode('utf-8')).hexdigest().upper()[:16]
    if dry:
        print('dry | lines', t.count(NL), '| sha16', sha)
        if len(sys.argv) > 2:
            with open(sys.argv[2], 'w', encoding='utf-8', newline=NL) as fh:
                fh.write(t)
        return
    open(OUT, 'w', encoding='utf-8', newline=NL).write(t)
    print('written draft12 | lines', t.count(NL), '| sha16', sha)


if __name__ == '__main__':
    main('--dry' in sys.argv)
