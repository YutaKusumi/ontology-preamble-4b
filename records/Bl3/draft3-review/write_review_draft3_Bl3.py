def leaves(o, p='$'):
    if isinstance(o, dict):
        for k, v in o.items():
            yield from leaves(v, p + '.' + k)
    elif isinstance(o, list):
        for i, v in enumerate(o):
            yield from leaves(v, '%s[%d]' % (p, i))
    else:
        yield p, o


