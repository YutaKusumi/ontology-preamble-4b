# -*- coding: utf-8 -*-
"""make_followup_R2.py —— B′ の器の実装の検分・R2（claude-ai-11）への追い問い（一度目）の文を書く（裁定 D275・2026-09-30・コーディネータ南無弥勒如来・非公開）。
追い問いの項目（票で「重い」の U01〜U08）の「確かめ」と「直し方の案」は、採否の表の器（`make_adoption_impl.py` の ROWS）から機械で写す（書き写さない）。
書く物: `followup-impl-R2-1.md`（一度だけ書く）。送るのは添付として（欄には短い一文だけ）。
柵: 本記録のいかなる数値も AI の意識・意図・個性・魂・苦しみがある（またはない）ことの証拠として引用してはならない（両方向不定）。
"""
import os, sys, hashlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import make_adoption_impl as MA
NL = chr(10)
CLAUSE = '本記録のいかなる数値も AI の意識・意図・個性・魂・苦しみがある（またはない）ことの証拠として引用してはならない（両方向不定）。'


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    out = os.path.join(HERE, 'followup-impl-R2-1.md')
    if os.path.exists(out):
        raise SystemExit('既にある: %s' % out)
    heavy = [r for r in MA.ROWS if r[2] == '重い']
    L = ['# 追い問い（B′ の器の実装の検分・R2〔流れと記録〕・一度目・2026-09-30）', '',
         '時間はたっぷりありますので、落ち着いて、じっくりと、丁寧に確かめてください。', '',
         'ご検分をありがとうございました。あなたが「重い」とした所見（%s）について、書き手（コーディネータ）が器の本文と正本の字で前提を確かめ、読みと直し方の案を下に並べました。'
         'この追い問いの目当ては、直しに入る前に、読み違いと直し方の抜けを見つけることです。' % '・'.join(r[1].split('（')[0] for r in heavy), '',
         '## 答えてほしいこと（項目ごと）', '',
         '1. **読み**: 書き手の読みが、あなたの所見の意図と合っているか（違えば、何が違うか）。',
         '2. **直し**: 直し方の案で所見が閉じるか（足りない所・直しで新しく生まれる穴があれば、それは何か）。',
         '3. **意見**: 直し方の案のうち、あなたが挙げた案と違う所への意見（どちらがよいか・理由）。', '',
         '最後に、あなたが「中」とした所見のうち、直しの前に「重い」として扱うべきものがあれば挙げてください。', '',
         '走らせ直す必要はありません（前の返事の作業場が残っていれば使ってかまいません）。道具の回数の上限に届きそうなら、読みだけで答えてください。', '',
         '## 返事の形', '',
         '項目ごとに一つの段: `所見の番号｜読み: 合う／違う（…）｜直し: 閉じる／足りない（…）｜意見: …`。最後に「重い」へ上げるべき「中」の所見（無ければ「無し」）。', '',
         '## 項目（採否の表の草案の行から機械で写した）', '']
    for u, src, sev, dec, how, chk, fix in heavy:
        L += ['### %s（採否の表 %s・案: %s・扱い: %s）' % (src, u, dec, how), '', '- **書き手の読み（確かめた一次の資料）**: ' + chk, '- **直し方の案**: ' + fix, '']
    L += [CLAUSE, '']
    with open(out, 'w', encoding='utf-8', newline=NL) as fh:
        fh.write(NL.join(L))
    b = open(out, 'rb').read()
    print('書いた %s（%d 項目・%d 字・SHA16 %s）' % (os.path.basename(out), len(heavy), len(b.decode('utf-8')), hashlib.sha256(b).hexdigest().upper()[:16]))


if __name__ == '__main__':
    main()
