def flags_of(t, i, q):
    line_start = t.rfind(NL, 0, i) + 1
    prefix = t[line_start:i].replace('**', '').strip()
    mid = bool(prefix) and not prefix.endswith(END_OK) and not re.match(r'^(\d+\.|-)$', prefix)
    dem = q.startswith(DEM)
